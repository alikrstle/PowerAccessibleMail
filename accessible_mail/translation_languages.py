PRIORITY_LANGUAGE_CODES = (
    "ar", "en", "fr", "es", "tr", "hi", "de", "pt", "zh-CN",
    "ru", "ur", "fa", "ja", "ko", "it",
)


def ordered_language_codes(saved=()) -> list[str]:
    available = set(TRANSLATION_LANGUAGES) - set(saved)
    priority = [code for code in PRIORITY_LANGUAGE_CODES if code in available]
    remaining = available - set(PRIORITY_LANGUAGE_CODES)
    return priority + sorted(remaining, key=lambda code: language_name(code).casefold())


def language_name(code: str) -> str:
    if get_language() == "ar":
        return ARABIC_NAMES.get(code, TRANSLATION_LANGUAGES.get(code, code))
    return TRANSLATION_LANGUAGES.get(code, code)


# A practical shortlist, not a statistical ranking of speaker counts.
MESSAGE_PRIORITY_CODES = PRIORITY_LANGUAGE_CODES + ("bn", "id", "vi", "ta", "te")


def message_language_codes() -> list[str]:
    priority = list(MESSAGE_PRIORITY_CODES)
    return priority + sorted(set(TRANSLATION_LANGUAGES) - set(priority),
                             key=lambda code: language_name(code).casefold())
